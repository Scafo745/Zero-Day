'use client';

import { FileDown } from 'lucide-react';
import type { StoredIncidentView } from '../hooks/useZeroTrace';

interface PostmortemExportProps {
  incident: StoredIncidentView;
  isVisible: boolean;
}

export function PostmortemExport({
  incident,
  isVisible,
}: PostmortemExportProps) {
  if (!isVisible) return null;

  const handleExport = () => {
    const { incidentId, detectedAt, result, process } = incident;
    const { analysis, developerPostmortem } = result;

    const actionItemsFormatted =
      developerPostmortem.actionItems && developerPostmortem.actionItems.length > 0
        ? developerPostmortem.actionItems.map((item) => `- ${item}`).join('\n')
        : '- No action items required.';

    const mitreFormatted =
      analysis.mitreTechniques && analysis.mitreTechniques.length > 0
        ? analysis.mitreTechniques
            .map(
              (t) => `- [${t}](https://attack.mitre.org/techniques/${t.replace('.', '/')})`
            )
            .join('\n')
        : 'None';

    const markdownContent = `# ${developerPostmortem.title}

**Incident ID:** \`${incidentId}\`  
**Detected At:** ${detectedAt}  
**Severity:** ${developerPostmortem.severity.toUpperCase()}  
**Threat Score:** ${analysis.threatScore} / 100 — **${analysis.verdict}**  

---

## Process Metadata

- **PID:** \`${process.pid}\` (Parent: \`${process.parentName}\`, PID \`${process.parentPid}\`)
- **User:** \`${process.user}\`
- **Working Directory:** \`${process.workingDirectory}\`
- **Command Line:**
\`\`\`bash
${process.commandLine}
\`\`\`
- **Outbound Destinations:** ${
      process.networkDestinations.length > 0
        ? process.networkDestinations.join(', ')
        : 'None'
    }
- **Files Touched:**
${process.filesTouched.map((f) => `  - \`${f}\``).join('\n')}

---

## Description

${developerPostmortem.description}

---

## Concrete Action Items

${actionItemsFormatted}

---

## MITRE ATT&CK Techniques

${mitreFormatted}

---

## Remediation Protocol

${analysis.remediation}

---

*Generated by ZeroTrace (Bauhaus Defense Rig) on ${new Date().toISOString()}*
`;

    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `zerotrace-postmortem-${incidentId.slice(0, 8)}.md`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <button
      onClick={handleExport}
      className="btn-bauhaus inline-flex items-center justify-center gap-2 bg-white hover:bg-canvas text-stark-black font-black text-sm uppercase tracking-wider py-3 px-5 border-4 border-stark-black shadow-[4px_4px_0px_0px_#121212]"
    >
      <FileDown className="w-4 h-4" />
      <span>EXPORT POST-MORTEM (MARKDOWN)</span>
    </button>
  );
}
